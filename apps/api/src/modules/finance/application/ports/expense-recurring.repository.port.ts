import type { DateOnly } from '../../../../shared/domain/business-date';
import type { EntityRef } from '../../../../shared/domain/entity-ref';
import type { Frequency, RecurringStatus } from '../../../../shared/domain/enums';
import type { SortSpec } from '../../../../shared/domain/list-query';
import type { MoneyString } from '../../../../shared/domain/money';
import type { Paginated } from '../../../../shared/domain/pagination';
import type { ExpenseCategoryView } from './expense.repository.port';

export const RECURRING_EXPENSE_REPOSITORY = Symbol('RECURRING_EXPENSE_REPOSITORY');

/** One `RecurringExpense` row. `usdRate` and `monthlyAmountUsd` are the snapshot of the last save (Δ10). */
export interface RecurringExpenseRecord {
  readonly id: string;
  readonly name: string;
  readonly vendor: string | null;
  readonly categoryId: string;
  readonly accountId: string | null;
  readonly projectId: string | null;
  readonly currency: string;
  readonly amount: MoneyString;
  readonly frequency: Frequency;
  readonly dayOfPeriod: number;
  readonly leadDays: number;
  readonly startDate: DateOnly;
  readonly endDate: DateOnly | null;
  readonly status: RecurringStatus;
  readonly lastGeneratedPeriodStart: DateOnly | null;
  readonly resumedOn: DateOnly | null;
  readonly usdRate: MoneyString;
  readonly monthlyAmountUsd: MoneyString;
  readonly createdAt: string;
}

export interface RecurringExpenseView extends RecurringExpenseRecord {
  readonly category: ExpenseCategoryView;
  readonly account: EntityRef | null;
  readonly project: EntityRef | null;
}

export interface RecurringExpenseFilter {
  readonly q?: string;
  readonly status?: readonly RecurringStatus[];
  readonly categoryId?: readonly string[];
  readonly frequency?: readonly Frequency[];
  readonly sort: SortSpec;
  readonly page: number;
  readonly pageSize: number;
}

export interface RecurringExpenseRepository {
  findById(id: string): Promise<RecurringExpenseRecord | null>;
  insert(record: RecurringExpenseRecord): Promise<void>;
  update(record: RecurringExpenseRecord): Promise<void>;
  view(id: string): Promise<RecurringExpenseView | null>;
  list(filter: RecurringExpenseFilter): Promise<Paginated<RecurringExpenseView>>;
  /** Ids of the `ACTIVO` schedules, ascending: what the daily step walks. */
  activeIds(): Promise<string[]>;
  /**
   * `periodStart` of every expense generated by each schedule, voided ones included (a voided period is
   * never generated again).
   */
  periodsOf(ids: readonly string[]): Promise<Map<string, DateOnly[]>>;
}
