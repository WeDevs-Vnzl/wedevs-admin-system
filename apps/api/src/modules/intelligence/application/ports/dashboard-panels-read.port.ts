import type { DateOnly } from '../../../../shared/domain/business-date';
import type {
  ActivityAction,
  BillingModel,
  RecurringStatus,
} from '../../../../shared/domain/enums';
import type { EntityRef } from '../../../../shared/domain/entity-ref';
import type { MoneyString } from '../../../../shared/domain/money';
import type { ClientMetricsView, ProjectMetricsView } from './entity-metrics-read.port';

export const DASHBOARD_PANELS_READ = Symbol('DASHBOARD_PANELS_READ');

/** An open invoice for the "due" panel; `balanceUsd` is the balance at the invoice's own snapshot rate (C16). */
export type DueInvoiceRow = {
  invoice: EntityRef;
  client: EntityRef;
  dueDate: DateOnly;
  currency: string;
  balance: MoneyString;
  balanceUsd: MoneyString;
};

export type InstallmentDueRow = {
  installment: EntityRef;
  project: EntityRef;
  amount: MoneyString;
  currency: string;
  dueDate: DateOnly | null;
};

export type ExpiringDocumentRow = { document: EntityRef; expiresAt: DateOnly };

/** A generated, still pending expense of a recurring schedule, valued by its own snapshot (C16). */
export type UpcomingRecurringExpenseRow = {
  expense: EntityRef;
  dueDate: DateOnly;
  amount: MoneyString;
  currency: string;
  amountUsd: MoneyString;
};

export type RecentActivityRow = {
  id: string;
  action: ActivityAction;
  entity: EntityRef | null;
  actorName: string | null;
  createdAt: Date;
};

/** A recurring charge with its stored monthly USD amount (DT-100). */
export type RecurringChargeRow = {
  monthlyAmountUsd: MoneyString;
  status: RecurringStatus;
};

export type AccountBalanceRow = { currency: string; balance: MoneyString };

export type ClientMetricsRecord = { metrics: ClientMetricsView; archived: boolean };
export type ProjectMetricsRecord = {
  metrics: ProjectMetricsView;
  archived: boolean;
  /** The plan bills a contract (`PRECIO_FIJO` or `MIXTO`), so "to invoice" applies (PRD §8.4.4). */
  model: BillingModel | null;
};

/**
 * Read side of the dashboard panels and the entity summaries (PRD §8.1, §8.4.4). Rows only: no
 * aggregation is decided here, the use cases do that and gate by role. Archived and soft-deleted rows never
 * reach a panel; the summaries report `archived` so the use case can apply the trash rule (C19).
 */
export interface DashboardPanelsReadPort {
  /** Open (`EMITIDA`, `PARCIAL`, `VENCIDA`), issued, with a balance: by due date then code, at most `limit`. */
  invoicesDue(limit: number): Promise<DueInvoiceRow[]>;

  /** `PENDIENTE` installments of live projects due on or before `until` (or undated is left out): by date, then order. */
  installmentsToInvoice(until: DateOnly): Promise<InstallmentDueRow[]>;

  /** Documents neither voided nor expired whose expiry falls in the inclusive range, by expiry. */
  documentsExpiring(from: DateOnly, until: DateOnly): Promise<ExpiringDocumentRow[]>;

  /** Pending expenses generated by a recurring expense, due on or before `until`, by due date. */
  upcomingRecurringExpenses(until: DateOnly): Promise<UpcomingRecurringExpenseRow[]>;

  /** The newest `limit` activity entries (newest first, ties by id descending). */
  recentActivity(limit: number): Promise<RecentActivityRow[]>;

  /** Recurring charges whose dates cover `date` (`startDate` ≤ date, no `endDate` or `endDate` ≥ date). */
  recurringChargesAt(date: DateOnly): Promise<RecurringChargeRow[]>;

  /** Active accounts' stored balances, in each account's currency. */
  activeAccountBalances(): Promise<AccountBalanceRow[]>;

  /** `null` when the id is unknown. */
  clientMetrics(clientId: string): Promise<ClientMetricsRecord | null>;

  /** `null` when the id is unknown. */
  projectMetrics(projectId: string): Promise<ProjectMetricsRecord | null>;
}
