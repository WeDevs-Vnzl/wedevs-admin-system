import { z } from "./zod";
import {
  VALIDATION_MESSAGES,
  dateOnlySchema,
  entityRefSchema,
  idSchema,
  listQuerySchema,
} from "./common";
import { documentFormatSchema, documentStatusSchema, shareEventSchema } from "./enums";
import { localeSchema } from "./preferences";
import { facetOf, optionalText, requiredText, timestampSchema, withSortFields } from "./tags";
import { userRefSchema } from "./users";

/**
 * Share links and the public portal (PRD §8.11; DT-42, DT-45, C22).
 *
 * A link shares one or more documents with outsiders through `/s/<token>`. Each document is pinned to
 * a concrete version (`versionId`) or follows the latest one (`versionId: null`) and may require an
 * **access key** (P5): the visitor must enter it before viewing or downloading that document.
 *
 * Access-key contract (security, C5/C22):
 * - The key is generated by the server, stored only as a `scrypt` hash, and returned **once** — in the
 *   result DTO of `createShareLink` / `updateShareLink` (`generatedKeys`) or `setShareDocumentAccessKey`
 *   (`accessKey`). **No read DTO** (`ShareLinkDetailDTO`, list rows, access-log rows, portal DTOs) has a
 *   key or hash field; they only say `requiresAccessKey` and `accessKeyUpdatedAt`.
 * - The visitor submits the key with `unlockSharedDocument` (min length 8). Errors are `ACCESS_KEY_INVALID`
 *   (wrong key) and `ACCESS_KEY_LOCKED` (5 failures per link, document and IP within 15 minutes → refused
 *   for 15 minutes). A locked document that was not unlocked answers `FORBIDDEN` on view and download.
 * - The unlock state lives in a signed cookie handled by the public action adapter; services receive the
 *   already-unlocked document ids (and the IP hash / user agent) as **server-only** input and never see
 *   the cookie. Clients can send only the `*ActionSchema` fields (see "Inputs: portal").
 */

// ───────────────────────────── Constants and primitives ─────────────────────────────

/** Share tokens are 32 random bytes in base64url: 43 characters. */
export const SHARE_TOKEN_LENGTH = 43;
export const shareTokenSchema = z
  .string()
  .regex(new RegExp(`^[A-Za-z0-9_-]{${SHARE_TOKEN_LENGTH}}$`), VALIDATION_MESSAGES.invalidFormat);
export type ShareToken = z.infer<typeof shareTokenSchema>;

/** Minimum length of an access key the visitor can submit (DT-45). */
export const ACCESS_KEY_MIN_LENGTH = 8;
export const ACCESS_KEY_MAX_LENGTH = 128;
/** Lockout policy shown by the portal UI (enforced by the service in Hito 2). */
export const ACCESS_KEY_MAX_FAILED_ATTEMPTS = 5;
export const ACCESS_KEY_LOCKOUT_MINUTES = 15;

/** Key typed by the visitor. Surrounding whitespace (pasted keys) is trimmed before the length check. */
export const accessKeyInputSchema = z
  .string()
  .trim()
  .min(ACCESS_KEY_MIN_LENGTH, VALIDATION_MESSAGES.tooShort)
  .max(ACCESS_KEY_MAX_LENGTH, VALIDATION_MESSAGES.tooLong);

/** Presigned download URLs live 5 minutes (C23). */
export const SHARE_DOWNLOAD_TTL_SECONDS = 300;

export const SHARE_STATUS_VALUES = ["ACTIVE", "REVOKED", "EXPIRED"] as const;
export const shareStatusSchema = z.enum(SHARE_STATUS_VALUES);
export type ShareStatus = z.infer<typeof shareStatusSchema>;

export const ACCESS_KEY_ACTION_VALUES = ["generate", "regenerate", "remove"] as const;
export const accessKeyActionSchema = z.enum(ACCESS_KEY_ACTION_VALUES);
export type AccessKeyAction = z.infer<typeof accessKeyActionSchema>;

/** Events a visitor can record directly; `UNLOCK`/`UNLOCK_FAILED` are logged by the unlock service. */
export const RECORDABLE_SHARE_EVENT_VALUES = ["VIEW", "DOWNLOAD"] as const;
export const recordableShareEventSchema = z.enum(RECORDABLE_SHARE_EVENT_VALUES);
export type RecordableShareEvent = z.infer<typeof recordableShareEventSchema>;

// ───────────────────────────── Inputs: management ─────────────────────────────

/** A document inside a link: latest version (`versionId: null`) or pinned, with an optional key. */
export const shareDocumentInputSchema = z.object({
  documentId: idSchema,
  /** `null` = always the current version. */
  versionId: idSchema.nullable().default(null),
  /** When `true` and the document has no key yet, a key is generated and returned once. */
  requiresAccessKey: z.boolean().default(false),
});
export type ShareDocumentInput = z.infer<typeof shareDocumentInputSchema>;

/** At least one document, none repeated; the array order is the display order. */
const shareDocumentsInputSchema = z
  .array(shareDocumentInputSchema)
  .min(1)
  .max(50)
  .refine((docs) => new Set(docs.map((d) => d.documentId)).size === docs.length, {
    message: VALIDATION_MESSAGES.invalidOption,
  });

const shareFieldsShape = {
  title: requiredText(200),
  message: optionalText(2000),
  /** Personalizes the portal header. */
  clientId: idSchema.optional(),
  documents: shareDocumentsInputSchema,
  allowDownload: z.boolean().default(true),
  locale: localeSchema.default("es"),
  /** Last valid day (Caracas); no value = never expires. */
  expiresAt: dateOnlySchema.optional(),
};

/** `createShareLink`: the token is generated by the service (CSPRNG, 43 chars). */
export const createShareLinkInputSchema = z.object(shareFieldsShape);
export type CreateShareLinkInput = z.infer<typeof createShareLinkInputSchema>;
export type CreateShareLinkFormValues = z.input<typeof createShareLinkInputSchema>;

/**
 * `updateShareLink`: the edit form submits every field; `documents` replaces the document list (add,
 * remove, re-pin). A document that already has a key keeps it; `requiresAccessKey: true` on a document
 * without one generates a key; `false` on a keyed one removes it.
 */
export const updateShareLinkInputSchema = z.object({ id: idSchema, ...shareFieldsShape });
export type UpdateShareLinkInput = z.infer<typeof updateShareLinkInputSchema>;

/** `revokeShareLink`: sets `revokedAt`; the portal then answers the generic 404. */
export const revokeShareLinkInputSchema = z.object({ id: idSchema });
export type RevokeShareLinkInput = z.infer<typeof revokeShareLinkInputSchema>;

/**
 * `setShareDocumentAccessKey`: `generate` (document has no key), `regenerate` (replace the key; old
 * unlock cookies stop working for new sessions) or `remove` (document becomes open).
 */
export const setShareDocumentAccessKeyInputSchema = z.object({
  shareLinkId: idSchema,
  documentId: idSchema,
  action: accessKeyActionSchema,
});
export type SetShareDocumentAccessKeyInput = z.infer<typeof setShareDocumentAccessKeyInputSchema>;

export const shareIdInputSchema = z.object({ id: idSchema });
export type ShareIdInput = z.infer<typeof shareIdInputSchema>;

// ───────────────────────────── Filters ─────────────────────────────

export const SHARE_SORT_FIELDS = [
  "title",
  "status",
  "expiresAt",
  "viewCount",
  "downloadCount",
  "lastAccessedAt",
  "createdAt",
] as const;

/** `/documents/shares` and the "Compartir" tab of a document (`documentId`). */
export const shareFilterSchema = withSortFields(
  listQuerySchema.extend({
    status: facetOf(shareStatusSchema),
    clientId: facetOf(idSchema),
    /** Links that include this document. */
    documentId: idSchema.optional(),
    /** Links with at least one key-protected document. */
    hasAccessKeys: z.union([z.boolean(), z.stringbool()]).optional(),
    createdFrom: dateOnlySchema.optional(),
    createdTo: dateOnlySchema.optional(),
  }),
  SHARE_SORT_FIELDS,
);
export type ShareFilter = z.infer<typeof shareFilterSchema>;
export type ShareFilterInput = z.input<typeof shareFilterSchema>;

export const SHARE_ACCESS_LOG_SORT_FIELDS = ["createdAt", "event"] as const;

/** Access-log table of one link. */
export const shareAccessLogFilterSchema = withSortFields(
  listQuerySchema.extend({
    shareLinkId: idSchema,
    event: facetOf(shareEventSchema),
    documentId: idSchema.optional(),
    from: dateOnlySchema.optional(),
    to: dateOnlySchema.optional(),
  }),
  SHARE_ACCESS_LOG_SORT_FIELDS,
);
export type ShareAccessLogFilter = z.infer<typeof shareAccessLogFilterSchema>;
export type ShareAccessLogFilterInput = z.input<typeof shareAccessLogFilterSchema>;

// ───────────────────────────── DTOs: management (read) ─────────────────────────────

const counter = z.number().int().nonnegative();

/** Counters shown on the link (PRD §8.11 "Trazabilidad", DT-45). */
export const shareCountersSchema = z.object({
  viewCount: counter,
  downloadCount: counter,
  unlockCount: counter,
  failedUnlockCount: counter,
});
/** A document of a link, as the owner sees it. No key, no hash: only whether a key is required. */
export const shareDocumentSchema = z.object({
  /** `{ id, code, label (title), type: "DOCUMENT" }`. */
  document: entityRefSchema,
  documentStatus: documentStatusSchema,
  /** Pinned version; `null` = follows the latest. */
  versionId: idSchema.nullable(),
  isLatest: z.boolean(),
  /** Version the visitor currently gets. */
  versionNumber: z.number().int().positive().nullable(),
  format: documentFormatSchema.nullable(),
  order: z.number().int().nonnegative(),
  requiresAccessKey: z.boolean(),
  /** When the key was last generated or regenerated; `null` without a key. */
  accessKeyUpdatedAt: timestampSchema.nullable(),
  counters: shareCountersSchema,
});
export type ShareDocumentDTO = z.infer<typeof shareDocumentSchema>;

export const shareLinkDetailSchema = z.object({
  id: idSchema,
  /** Part of the public URL; the owner needs it to copy the link and build the QR code. */
  token: shareTokenSchema,
  /** Full public URL (`<APP_URL>/s/<token>`). */
  url: z.string(),
  title: z.string(),
  message: z.string().nullable(),
  client: entityRefSchema.nullable(),
  locale: localeSchema,
  allowDownload: z.boolean(),
  expiresAt: dateOnlySchema.nullable(),
  revokedAt: timestampSchema.nullable(),
  status: shareStatusSchema,
  counters: shareCountersSchema,
  lastAccessedAt: timestampSchema.nullable(),
  documents: z.array(shareDocumentSchema),
  createdBy: userRefSchema,
  createdAt: timestampSchema,
});
export type ShareLinkDetailDTO = z.infer<typeof shareLinkDetailSchema>;

/** Row of `/documents/shares`. */
export const shareLinkListRowSchema = z.object({
  id: idSchema,
  title: z.string(),
  client: entityRefSchema.nullable(),
  documentCount: counter,
  /** Documents of the link that require a key. */
  protectedDocumentCount: counter,
  status: shareStatusSchema,
  expiresAt: dateOnlySchema.nullable(),
  counters: shareCountersSchema,
  lastAccessedAt: timestampSchema.nullable(),
  createdBy: userRefSchema,
  createdAt: timestampSchema,
});
export type ShareLinkListRowDTO = z.infer<typeof shareLinkListRowSchema>;

/**
 * Row of a link's access log. The IP is never exposed: `visitor` is a short fingerprint (a prefix of the
 * salted hash) that lets the owner tell visitors apart.
 */
export const shareAccessLogRowSchema = z.object({
  id: idSchema,
  shareLinkId: idSchema,
  event: shareEventSchema,
  documentId: idSchema.nullable(),
  documentTitle: z.string().nullable(),
  visitor: z.string().max(12),
  userAgent: z.string().nullable(),
  createdAt: timestampSchema,
});
export type ShareAccessLogRowDTO = z.infer<typeof shareAccessLogRowSchema>;

// ───────────────────────────── DTOs: results that carry a clear key (once) ─────────────────────────────

/** A freshly generated key. The only place besides `SetShareDocumentAccessKeyResultDTO` a clear key appears. */
export const generatedAccessKeySchema = z.object({
  documentId: idSchema,
  accessKey: z.string().min(ACCESS_KEY_MIN_LENGTH).max(ACCESS_KEY_MAX_LENGTH),
});
export type GeneratedAccessKeyDTO = z.infer<typeof generatedAccessKeySchema>;

/**
 * Output of `createShareLink` and `updateShareLink`: the link plus the keys generated by this call. The
 * UI shows them once ("copy now, it cannot be shown again").
 */
export const shareLinkMutationResultSchema = z.object({
  share: shareLinkDetailSchema,
  generatedKeys: z.array(generatedAccessKeySchema),
});
export type ShareLinkMutationResultDTO = z.infer<typeof shareLinkMutationResultSchema>;

/**
 * Output of `setShareDocumentAccessKey`. `accessKey` is the clear key and is non-null only for
 * `generate` / `regenerate`; `remove` and every later read carry no key.
 */
export const setShareDocumentAccessKeyResultSchema = z
  .object({
    shareLinkId: idSchema,
    documentId: idSchema,
    action: accessKeyActionSchema,
    requiresAccessKey: z.boolean(),
    accessKeyUpdatedAt: timestampSchema.nullable(),
    accessKey: z.string().min(ACCESS_KEY_MIN_LENGTH).max(ACCESS_KEY_MAX_LENGTH).nullable(),
  })
  .refine((result) => (result.action === "remove") === (result.accessKey === null), {
    message: VALIDATION_MESSAGES.invalidOption,
    path: ["accessKey"],
  });
export type SetShareDocumentAccessKeyResultDTO = z.infer<
  typeof setShareDocumentAccessKeyResultSchema
>;
