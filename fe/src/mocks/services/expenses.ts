/** An active category of the two-level catalog, with its parent (never trust a client id). */
function categoryRefOf(db: MockStore, id: string): ExpenseCategoryRef {
  const row = db.expenseCategories.find((item) => item.id === id && item.active);
  if (!row) throw invalid("categoryId", EXPENSE_ERRORS.categoryUnavailable);
  const parent = row.parentId
    ? db.expenseCategories.find((item) => item.id === row.parentId)
    : undefined;
  return {
    id: row.id,
    name: row.name,
    nameEn: row.nameEn,
    parent: parent ? { id: parent.id, name: parent.name, nameEn: parent.nameEn } : null,
  };
}

/** An active company account; the payment account of a paid expense (§8.8). */
function accountRowOf(db: MockStore, id: string, field = "accountId") {
  const row = db.accounts.find((item) => item.id === id);
  if (!row || !row.active) throw invalid(field, EXPENSE_ERRORS.accountUnavailable);
  return row;
}

/** A live (not archived) project of the expense's imputation (§8.8). */
function projectRefOf(db: MockStore, id: string): EntityRef {
  const row = db.projects.find((item) => item.id === id);
  if (!row || row.archivedAt) throw invalid("projectId", EXPENSE_ERRORS.projectUnavailable);
  return { id: row.id, code: row.code, label: row.name, type: "PROJECT" };
}

/** The attached receipt, when the id names an existing file (the upload itself is H1 mock). */
function receiptOf(db: MockStore, fileId: string | undefined) {
  if (fileId === undefined) return null;
  const file = db.files.find((item) => item.id === fileId);
  if (!file) throw invalid("receiptFileId", EXPENSE_ERRORS.receiptUnavailable);
  return structuredClone(file);
}

/** §9.7: when the account currency differs, the debit in that currency (`accountAmount`) is required. */
function checkAccountAmount(
  currency: string,
  accountCurrency: string,
  accountAmount: MoneyString | undefined,
): void {
  if (accountCurrency !== currency && accountAmount === undefined) {
    throw invalid("accountAmount", EXPENSE_MESSAGES.accountAmountRequired);
  }
}

function isOverdue(expense: ExpenseDetailDTO, today: DateOnly): boolean {
  return expense.status === "PENDIENTE" && expense.dueDate !== null && expense.dueDate < today;
}

function toListRow(expense: ExpenseDetailDTO, today: DateOnly): ExpenseListRow {
  return {
    id: expense.id,
    code: expense.code,
    date: expense.date,
    dueDate: expense.dueDate,
    description: expense.description,
    vendor: expense.vendor,
    category: structuredClone(expense.category),
    account: expense.account ? { ...expense.account } : null,
    project: expense.project ? { ...expense.project } : null,
    currency: expense.currency,
    amount: expense.amount,
    amountUsd: expense.amountUsd,
    status: expense.status,
    overdue: isOverdue(expense, today),
    recurring: expense.recurring,
  };
}

function toDetail(expense: ExpenseDetailDTO, today: DateOnly): ExpenseDetailDTO {
  return { ...structuredClone(expense), overdue: isOverdue(expense, today) };
}

/** The USD value of an amount in `currency` at the rate of `today`; `null` without a rate. */
function usdOf(db: MockStore, amount: MoneyString, currency: string, today: DateOnly) {
  if (currency === "USD") return amount;
  const rate = selectRate(db.exchangeRates, today, currency);
  return rate ? toUsd(amount, rate.usdRate) : null;
}

/** Months as `YYYY-MM`, oldest first, ending with the month of `today`. */
function lastMonths(today: DateOnly, count: number): string[] {
  const date = parseDateOnly(today);
  const keys: string[] = [];
  for (let back = count - 1; back >= 0; back -= 1) {
    const month = new Date(Date.UTC(date.getUTCFullYear(), date.getUTCMonth() - back, 1));
    keys.push(month.toISOString().slice(0, 7));
  }
  return keys;
}

/** The month an expense is counted in: its payment date when paid (§8.8, the monthly spend of §8.8 Overview). */
function monthOf(expense: ExpenseDetailDTO): string {
  return (expense.paidAt ?? expense.date).slice(0, 7);
}

