/** Changing the amount affects only the periods not generated yet; generated expenses keep their own amount. */
export async function updateRecurringExpense(
  ctx: MockServiceContext,
  input: UpdateRecurringExpenseInput,
): Promise<RecurringExpenseDTO> {
  const { db } = ctx;
  const row = findRecurring(db, input.id);
  if (row.status === "FINALIZADO") {
    throw new ServiceError("CONFLICT", { message: EXPENSE_ERRORS.recurringFinished });
  }
  const category = categoryRefOf(db, input.categoryId);
  const accountRow = input.accountId ? accountRowOf(db, input.accountId) : undefined;
  row.name = input.name;
  row.vendor = input.vendor ?? null;
  row.category = category;
  row.account = accountRow ? refOf("ACCOUNT", accountRow.id, accountRow.name) : null;
  row.project = input.projectId ? projectRefOf(db, input.projectId) : null;
  row.currency = input.currency;
  row.amount = roundMoney(input.amount);
  row.frequency = input.frequency;
  row.dayOfPeriod = input.dayOfPeriod;
  row.leadDays = input.leadDays;
  row.startDate = input.startDate;
  row.endDate = input.endDate ?? null;
  syncRecurring(db);
  await logActivity(mockTx(ctx), {
    actorType: "USER",
    actorId: ctx.user.id,
    action: "UPDATE",
    entityType: "RECURRING_EXPENSE",
    entityId: row.id,
    entityLabel: row.name,
  });
  return structuredClone(row);
}

/** Pauses, resumes or finishes a schedule. A finished schedule is final. */
export async function setRecurringExpenseStatus(
  ctx: MockServiceContext,
  input: SetRecurringExpenseStatusInput,
): Promise<RecurringExpenseDTO> {
  const { db } = ctx;
  const row = findRecurring(db, input.id);
  if (row.status === input.status) return structuredClone(row);
  if (row.status === "FINALIZADO") {
    throw new ServiceError("CONFLICT", { message: EXPENSE_ERRORS.recurringFinished });
  }
  const previous = row.status;
  row.status = input.status;
  syncRecurring(db);
  await logActivity(mockTx(ctx), {
    actorType: "USER",
    actorId: ctx.user.id,
    action: "STATUS_CHANGE",
    entityType: "RECURRING_EXPENSE",
    entityId: row.id,
    entityLabel: row.name,
    changes: { status: [previous, input.status] },
  });
  return structuredClone(row);
}

/**
 * The daily job of the recurring expenses (HU-17 CA1): generates every due pending expense of every active
 * schedule as of the business day, catching up every missed period. Running it twice on the same day creates
 * nothing the second time (CA1: no duplicates). Paused and finished schedules generate nothing.
 */
export async function runRecurringExpenseGeneration(
  ctx: MockServiceContext,
): Promise<RecurringExpenseGenerationResult> {
  const { db } = ctx;
  const today = todayInCaracas(ctx.now);
  const periodStarts: DateOnly[] = [];
  for (const row of db.recurringExpenses) {
    if (row.status !== "ACTIVO") continue;
    const created = generatePeriods(db, row, today, ctx.now);
    if (created.length === 0) continue;
    periodStarts.push(...created);
    await logActivity(mockTx(ctx), {
      actorType: "SYSTEM",
      actorId: null,
      action: "SYSTEM_JOB",
      entityType: "RECURRING_EXPENSE",
      entityId: row.id,
      entityLabel: row.name,
      metadata: { created: created.length },
    });
  }
  if (periodStarts.length > 0) {
    syncRecurring(db);
    deriveMockStore(db);
  }
  return { created: periodStarts.length, periodStarts };
}
