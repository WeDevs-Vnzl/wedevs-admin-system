/**
 * `/expenses` overview (DT-25, PRD §8.8): paid spend per month and per root category (USD, the last six months),
 * the committed monthly recurring spend (USD, active schedules normalized to a month, §8.13.2) and the upcoming
 * pending expenses.
 */
export async function getExpensesOverview(ctx: MockServiceContext): Promise<ExpensesOverviewDTO> {
  const { db } = ctx;
  const today = todayInCaracas(ctx.now);
  const periods = lastMonths(today, OVERVIEW_MONTHS);
  const paidInWindow = db.expenses.filter(
    (item) => item.status === "PAGADO" && periods.includes(monthOf(item)),
  );
  const rootOf = (item: ExpenseDetailDTO) => item.category.parent ?? item.category;

  const roots = new Map<string, string>();
  for (const item of paidInWindow) roots.set(rootOf(item).id, rootOf(item).name);
  const series = [...roots.entries()]
    .sort((a, b) => a[1].localeCompare(b[1]))
    .map(([id, label]) => {
      const inRoot = paidInWindow.filter((item) => rootOf(item).id === id);
      return {
        id,
        label,
        values: periods.map((period) =>
          sumMoney(inRoot.filter((item) => monthOf(item) === period).map((item) => item.amountUsd)),
        ),
      };
    });
  const byCategory = series.map((item) => ({
    key: item.id,
    label: item.label,
    value: sumMoney(item.values),
  }));

  const committed = db.recurringExpenses
    .filter((row) => row.status === "ACTIVO")
    .map((row) => usdOf(db, normalizeToMonth(row.amount, row.frequency), row.currency, today))
    .filter((value): value is MoneyString => value !== null);

  const upcoming = db.expenses
    .filter((item) => item.status === "PENDIENTE")
    .sort((a, b) => (a.dueDate ?? a.date).localeCompare(b.dueDate ?? b.date))
    .slice(0, UPCOMING_LIMIT)
    .map((item) => toListRow(item, today));

  return {
    byMonthAndCategory: { periods, series },
    byCategory,
    committedMonthly: sumMoney(committed),
    upcoming,
  };
}

/**
 * The expense table (`/expenses/list`, DT-25): voided ones included so they stay visible. Every filter is optional;
 * `q` matches code, description, vendor, category, account and project.
 */
export async function listExpenses(
  ctx: MockServiceContext,
  input: ExpenseListInput,
): Promise<Paginated<ExpenseListRow>> {
  const today = todayInCaracas(ctx.now);
  const statuses =
    input.status === undefined ? undefined : ([] as ExpenseStatus[]).concat(input.status);
  const rows = ctx.db.expenses
    .filter((item) => !statuses || statuses.includes(item.status))
    .filter(
      (item) =>
        !input.categoryId ||
        input.categoryId.includes(item.category.id) ||
        (item.category.parent !== null && input.categoryId.includes(item.category.parent.id)),
    )
    .filter(
      (item) => !input.accountId || (!!item.account && input.accountId.includes(item.account.id)),
    )
    .filter(
      (item) => !input.projectId || (!!item.project && input.projectId.includes(item.project.id)),
    )
    .filter((item) => !input.dateFrom || item.date >= input.dateFrom)
    .filter((item) => !input.dateTo || item.date <= input.dateTo)
    .filter((item) => !input.recurringOnly || item.recurring)
    .map((item) => toListRow(item, today));
  return listRows(
    rows,
    {
      page: input.page ?? 1,
      pageSize: input.pageSize ?? DEFAULT_PAGE_SIZE,
      sort: input.sort,
      q: input.q,
    },
    expenseSpec,
  );
}

