// ───────────────────────────── Recurring schedule (HU-17, §8.13.2) ─────────────────────────────

/** Periods already generated for a recurring expense: their `periodStart`s. */
function generatedPeriods(db: MockStore, recurringId: string): DateOnly[] {
  return db.expenses.flatMap((item) =>
    item.recurringExpense?.id === recurringId && item.periodStart !== null
      ? [item.periodStart]
      : [],
  );
}

function scheduleOf(
  row: RecurringExpenseDTO,
  status: RecurringSchedule["status"],
): RecurringSchedule {
  return {
    frequency: row.frequency,
    startDate: row.startDate,
    endDate: row.endDate,
    billingDay: row.dayOfPeriod,
    leadDays: row.leadDays,
    status,
  };
}

/**
 * Keeps the derived fields of every recurring expense in step with its generated expenses: the last generated
 * period and the next period still to generate (`null` when finished). Paused schedules still show their next
 * period; the generation itself skips them.
 */
function syncRecurring(db: MockStore): void {
  for (const row of db.recurringExpenses) {
    const existing = generatedPeriods(db, row.id);
    row.lastGeneratedPeriodStart = [...existing].sort().at(-1) ?? null;
    row.nextDueDate =
      row.status === "FINALIZADO"
        ? null
        : (dueRecurringPeriods(scheduleOf(row, "ACTIVO"), existing, NO_LIMIT)[0]?.periodStart ??
          null);
  }
}

/**
 * Creates the pending expenses of one recurring expense that are due by `asOf`: one period per step, each with
 * its generation day reached, never a period twice (HU-17 CA1). Every due period is caught up (T5 pattern); a
 * paused or finished schedule generates nothing. A non-USD schedule without a rate on `asOf` waits for one.
 */
function generatePeriods(
  db: MockStore,
  row: RecurringExpenseDTO,
  asOf: DateOnly,
  now: Date,
): DateOnly[] {
  const created: DateOnly[] = [];
  for (let guard = 0; guard < MAX_PERIODS_PER_RUN; guard += 1) {
    const [due] = dueRecurringPeriods(
      scheduleOf(row, row.status),
      generatedPeriods(db, row.id),
      asOf,
    );
    if (!due) break;
    const usdRate =
      row.currency === "USD" ? "1" : selectRate(db.exchangeRates, asOf, row.currency)?.usdRate;
    if (usdRate === undefined) break;
    const amount = roundMoney(row.amount);
    const stamp = now.toISOString();
    db.expenses.push({
      id: nextMockId(db.idCounters, "exp", (value) =>
        db.expenses.some((item) => item.id === value),
      ),
      code: nextMockCode(db.sequences, "GAS"),
      date: due.generateOn,
      dueDate: due.periodStart,
      description: `${row.name} · ${due.periodStart}`,
      vendor: row.vendor,
      category: structuredClone(row.category),
      account: row.account ? { ...row.account } : null,
      project: row.project ? { ...row.project } : null,
      currency: row.currency,
      amount,
      amountUsd: toUsd(amount, usdRate),
      status: "PENDIENTE",
      overdue: false,
      recurring: true,
      usdRate,
      paidAt: null,
      accountAmount: null,
      receiptFileId: null,
      receipt: null,
      recurringExpense: refOf("RECURRING_EXPENSE", row.id, row.name),
      periodStart: due.periodStart,
      createdAt: stamp,
      updatedAt: stamp,
      createdById: null,
    });
    created.push(due.periodStart);
  }
  return created;
}

