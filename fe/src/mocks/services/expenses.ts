/**
 * Creates an expense, pending or already paid. A paid one needs its account; a foreign-currency debit needs the
 * amount debited in the account currency (`accountAmount`, §9.7). The USD snapshot is taken from the rate given.
 */
export async function createExpense(
  ctx: MockServiceContext,
  input: CreateExpenseInput,
): Promise<ExpenseDetailDTO> {
  const { db } = ctx;
  const today = todayInCaracas(ctx.now);
  const category = categoryRefOf(db, input.categoryId);
  const accountRow = input.accountId ? accountRowOf(db, input.accountId) : undefined;
  if (input.status === "PAGADO" && !accountRow) {
    throw invalid("accountId", EXPENSE_MESSAGES.accountRequiredForPaid);
  }
  if (input.status === "PAGADO" && accountRow) {
    checkAccountAmount(input.currency, accountRow.currency, input.accountAmount);
  }
  const project = input.projectId ? projectRefOf(db, input.projectId) : null;
  const amount = roundMoney(input.amount);
  const now = ctx.now.toISOString();
  const row: ExpenseDetailDTO = {
    id: nextMockId(db.idCounters, "exp", (value) => db.expenses.some((item) => item.id === value)),
    code: nextMockCode(db.sequences, "GAS"),
    date: input.date,
    dueDate: input.dueDate ?? null,
    description: input.description,
    vendor: input.vendor ?? null,
    category,
    account: accountRow ? refOf("ACCOUNT", accountRow.id, accountRow.name) : null,
    project,
    currency: input.currency,
    amount,
    amountUsd: toUsd(amount, input.usdRate),
    status: input.status,
    overdue: false,
    recurring: false,
    usdRate: input.usdRate,
    paidAt: input.status === "PAGADO" ? (input.paidAt ?? input.date) : null,
    accountAmount: input.accountAmount ?? null,
    receiptFileId: input.receiptFileId ?? null,
    receipt: receiptOf(db, input.receiptFileId),
    recurringExpense: null,
    periodStart: null,
    createdAt: now,
    updatedAt: now,
    createdById: ctx.user.id,
  };
  db.expenses.push(row);
  deriveMockStore(db);
  await logExpense(ctx, "CREATE", row);
  return toDetail(row, today);
}

/**
 * "Marcar como pagado" (HU-17 CA2): confirms a pending expense. The account is mandatory and the real amount and
 * rate may differ from the estimate; the USD snapshot is taken again from them (§9.2). A voided or paid expense
 * is not marked again.
 */
export async function markExpensePaid(
  ctx: MockServiceContext,
  input: MarkExpensePaidInput,
): Promise<ExpenseDetailDTO> {
  const { db } = ctx;
  const row = findExpense(db, input.id);
  if (row.status === "ANULADO")
    throw new ServiceError("CONFLICT", { message: EXPENSE_ERRORS.voided });
  if (row.status !== "PENDIENTE") {
    throw new ServiceError("CONFLICT", { message: EXPENSE_ERRORS.notPending });
  }
  const accountRow = accountRowOf(db, input.accountId);
  checkAccountAmount(input.currency, accountRow.currency, input.accountAmount);

  const amount = roundMoney(input.amount);
  const previous = row.status;
  Object.assign(row, {
    status: "PAGADO" as const,
    account: refOf("ACCOUNT", accountRow.id, accountRow.name),
    paidAt: input.paidAt,
    currency: input.currency,
    amount,
    amountUsd: toUsd(amount, input.usdRate),
    usdRate: input.usdRate,
    accountAmount: input.accountAmount ?? null,
    receiptFileId: input.receiptFileId ?? null,
    receipt: receiptOf(db, input.receiptFileId),
    overdue: false,
    updatedAt: ctx.now.toISOString(),
  });
  deriveMockStore(db);
  await logExpense(ctx, "STATUS_CHANGE", row, { from: previous, to: "PAGADO" });
  return toDetail(row, todayInCaracas(ctx.now));
}

/**
 * Voids an expense (`ANULADO`). It leaves the account balance and the project margin; its period, if it came from
 * a recurring expense, is not generated again.
 */
export async function voidExpense(
  ctx: MockServiceContext,
  input: VoidExpenseInput,
): Promise<ExpenseDetailDTO> {
  const { db } = ctx;
  const row = findExpense(db, input.id);
  if (row.status === "ANULADO")
    throw new ServiceError("CONFLICT", { message: EXPENSE_ERRORS.voided });
  const previous = row.status;
  row.status = "ANULADO";
  row.overdue = false;
  row.updatedAt = ctx.now.toISOString();
  deriveMockStore(db);
  syncRecurring(db);
  await logExpense(ctx, "STATUS_CHANGE", row, {
    from: previous,
    to: "ANULADO",
    ...(input.reason ? { reason: input.reason } : {}),
  });
  return toDetail(row, todayInCaracas(ctx.now));
}

