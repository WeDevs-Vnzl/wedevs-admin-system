import { isDecimalString } from "./money";

/**
 * CSV serializer for the table export (PRD §12 `exportCsv`). Pure and framework-free: it turns rows into
 * text and knows nothing about entities, permissions or files.
 *
 * - RFC 4180: fields with `,`, `"`, CR or LF are quoted and `"` is doubled; records end with CRLF.
 * - UTF-8 BOM first, so Excel opens accents correctly.
 * - Formula-injection guard (OWASP): a string cell starting with `=`, `+`, `-`, `@`, tab or CR gets a
 *   leading `'` so a spreadsheet never evaluates it.
 * - Money columns (`type: "money"`) are decimal strings written verbatim (C15): never a JS number, never
 *   rounded, never locale-formatted (a decimal string such as `1234.50` is the cell, whatever the UI
 *   locale shows as `1.234,50`). Their value is validated as a decimal string, which is also why
 *   they skip the guard (a negative amount starts with `-` and must stay numeric).
 */

export const CSV_BOM = "﻿";
export const CSV_EOL = "\r\n";

/** First characters a spreadsheet treats as the start of a formula. */
const FORMULA_PREFIX = /^[=+\-@\t\r]/;

export type CsvColumnType = "text" | "money";

export interface CsvColumn {
  /** Property of the row; dotted paths read nested values (`client.label`). */
  key: string;
  /** Header cell, already translated by the caller. */
  header: string;
  /** `money` cells must be decimal strings and are written verbatim. Defaults to `text`. */
  type?: CsvColumnType;
}

export interface ToCsvOptions {
  /** Prepend the UTF-8 byte order mark. Defaults to `true`. */
  bom?: boolean;
}

function readPath(row: unknown, key: string): unknown {
  let node: unknown = row;
  for (const part of key.split(".")) {
    if (node === null || typeof node !== "object") return undefined;
    node = (node as Record<string, unknown>)[part];
  }
  return node;
}

/** Text of a non-money cell; `null`/`undefined` are empty. */
function textOf(value: unknown): string {
  if (value === null || value === undefined) return "";
  if (typeof value === "string") return value;
  if (typeof value === "number") {
    if (!Number.isFinite(value)) throw new RangeError("CSV cell is not a finite number");
    return String(value);
  }
  if (typeof value === "boolean") return value ? "true" : "false";
  if (value instanceof Date) return value.toISOString();
  throw new TypeError("CSV cell must be a string, number, boolean, Date, null or undefined");
}

/** Guards a text cell against spreadsheet formula injection. */
export function guardFormula(cell: string): string {
  return FORMULA_PREFIX.test(cell) ? `'${cell}` : cell;
}

/** RFC 4180 field: quoted only when it contains a delimiter, a quote or a line break. */
export function quoteCsvField(field: string): string {
  return /[",\r\n]/.test(field) ? `"${field.replaceAll('"', '""')}"` : field;
}

function cellOf(value: unknown, column: CsvColumn): string {
  if (column.type === "money") {
    if (value === null || value === undefined || value === "") return "";
    if (!isDecimalString(value)) {
      throw new TypeError(`CSV money column "${column.key}" needs a decimal string`);
    }
    return quoteCsvField(value);
  }
  // Only free text can smuggle a formula; numbers, booleans and dates are generated by us.
  const text = textOf(value);
  return quoteCsvField(typeof value === "string" ? guardFormula(text) : text);
}

/**
 * Serializes `rows` to CSV text: one header record built from `columns`, then one record per row, in
 * column order. Throws on repeated column keys, a money cell that is not a decimal string, or a cell
 * whose type cannot be written (object, function…). No rows yields only the header.
 */
export function toCsv(
  rows: readonly unknown[],
  columns: readonly CsvColumn[],
  options: ToCsvOptions = {},
): string {
  if (columns.length === 0) throw new RangeError("CSV needs at least one column");
  if (new Set(columns.map((column) => column.key)).size !== columns.length) {
    throw new RangeError("CSV columns must be unique");
  }

  const header = columns.map((column) => quoteCsvField(guardFormula(column.header)));
  const records = rows.map((row) =>
    columns.map((column) => cellOf(readPath(row, column.key), column)).join(","),
  );
  const body = [header.join(","), ...records].join(CSV_EOL) + CSV_EOL;
  return options.bom === false ? body : CSV_BOM + body;
}
